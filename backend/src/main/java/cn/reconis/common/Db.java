package cn.reconis.common;

import java.util.*;
import java.util.regex.Pattern;
import org.apache.ibatis.annotations.*;
import org.springframework.stereotype.Component;

@Component
public class Db {
  private static final Pattern INSERT_ID_OUTPUT =
      Pattern.compile("(?i)\\bOUTPUT\\s+INSERTED\\.id\\b");

  @Mapper
  public interface SqlMapper {
    @SelectProvider(type = Provider.class, method = "sql")
    @Options(flushCache = Options.FlushCachePolicy.TRUE, useCache = false)
    List<Map<String, Object>> query(@Param("sql") String sql, @Param("p") Map<String, Object> p);

    @SelectProvider(type = Provider.class, method = "sql")
    @Options(flushCache = Options.FlushCachePolicy.TRUE, useCache = false, timeout = 8)
    List<Map<String, Object>> search(@Param("sql") String sql, @Param("p") Map<String, Object> p);

    @UpdateProvider(type = Provider.class, method = "sql")
    int execute(@Param("sql") String sql, @Param("p") Map<String, Object> p);
  }

  public static class Provider {
    public String sql(Map<String, Object> p) {
      return p.get("sql").toString();
    }
  }

  private final SqlMapper mapper;

  public Db(SqlMapper mapper) {
    this.mapper = mapper;
  }

  public List<Map<String, Object>> list(String sql, Map<String, Object> p) {
    return mapper.query(sql, p).stream().map(Db::camel).toList();
  }

  public List<Map<String, Object>> search(String sql, Map<String, Object> p) {
    return mapper.search(sql, p).stream().map(Db::camel).toList();
  }

  public Map<String, Object> one(String sql, Map<String, Object> p) {
    var rows = list(sql, p);
    return rows.isEmpty() ? null : rows.getFirst();
  }

  public Map<String, Object> need(String sql, Map<String, Object> p) {
    var row = one(sql, p);
    if (row == null) throw Api.fail(404, "记录不存在或不可访问");
    return row;
  }

  public int exec(String sql, Map<String, Object> p) {
    return mapper.execute(sql, p);
  }

  public long insert(String sql, Map<String, Object> p) {
    var output = INSERT_ID_OUTPUT.matcher(sql);
    if (!output.find()) throw new IllegalArgumentException("插入语句必须返回 INSERTED.id");
    // SQL Server disallows a direct OUTPUT result when the INSERT has enabled triggers.
    // A table variable also keeps the returned id independent of identities generated by triggers.
    String statement =
        "DECLARE @reconis_inserted TABLE(id BIGINT); "
            + output.replaceFirst("OUTPUT INSERTED.id INTO @reconis_inserted")
            + "; SELECT id FROM @reconis_inserted;";
    var rows = list(statement, p);
    if (rows.isEmpty()) throw Api.fail(409, "未创建记录，请刷新后重试");
    if (rows.size() != 1) throw new IllegalStateException("单条插入返回了多条记录");
    return ((Number) rows.getFirst().get("id")).longValue();
  }

  public static long id(Map<String, Object> row, String k) {
    return Long.parseLong(row.get(k).toString());
  }

  public Map<String, Object> page(
      String from, String where, String sort, Map<String, Object> p, int page, int size) {
    page = Math.max(1, page);
    size = Math.clamp(size, 1, 100);
    p = new HashMap<>(p);
    p.put("offset", (page - 1) * size);
    p.put("size", size);
    var total = need("SELECT COUNT_BIG(*) total " + from + " WHERE " + where, p).get("total");
    return Map.of(
        "items",
        list(
            "SELECT * "
                + from
                + " WHERE "
                + where
                + " ORDER BY "
                + sort
                + " OFFSET #{p.offset} ROWS FETCH NEXT #{p.size} ROWS ONLY",
            p),
        "total",
        total,
        "page",
        page,
        "pageSize",
        size);
  }

  private static Map<String, Object> camel(Map<String, Object> row) {
    Map<String, Object> m = new LinkedHashMap<>();
    row.forEach(
        (k, v) -> {
          StringBuilder b = new StringBuilder();
          boolean upper = false;
          for (char c : k.toCharArray()) {
            if (c == '_') upper = true;
            else {
              b.append(upper ? Character.toUpperCase(c) : c);
              upper = false;
            }
          }
          m.put(b.toString(), v);
        });
    return m;
  }
}
